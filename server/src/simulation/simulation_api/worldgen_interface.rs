//! A world generation's interface to the simulation and the server
//! ([`WorldgenCode`]): what generates an area's cells, and what
//! lives on one, put there on its turn the first tick it is hot --
//! queued as any rule queues, under compares; and what the server is
//! asked of a world before or beside running it -- its numbers off a
//! window's sliders, a seed fit to start, its terrain. It is the
//! library of the type hooked into generating the world. The numbers
//! it generates by are the world's, each by name: whoever runs the
//! world hands them on, and knows nothing of them.

use crate::simulation::SimulationTickState;
use crate::chunk_storage::GeneratedArea;
use protocol::pipe::terrain::{DrawnHeightRange, Height, HeightsAsk, MapAnswer, MapAsk};
use utilities::tuning::Tuning;
use std::sync::Arc;

/// The numbers a world is generated by, each with its name: as its file
/// keeps them, and as a window's sliders give them.
pub type GenerationNumbers = [(String, u64)];

/// Writes the cells of an area of the world of a seed, as the numbers
/// say: made as its type is registered, with the IDs of the planes it
/// writes.
pub type GenerateCells = dyn Fn(&GenerationNumbers, u64, &mut GeneratedArea) + Send + Sync;
/// Queues on a superchunk's turn what lives on it, as the numbers say,
/// for the world of a seed: made as its type is registered, with the
/// IDs of what it makes.
pub type Populate = dyn Fn(&mut SimulationTickState, &GenerationNumbers, u64) + Send + Sync;

/// What generates a world, as the library of the type hooked into
/// generating it.
#[derive(Clone)]
pub struct WorldgenCode {
    /// Writes the cells of an area of the world of a seed, as the
    /// numbers say: the same whenever it is made.
    pub generate_cells: Arc<GenerateCells>,
    /// Queues on a superchunk's turn what lives on it, the first tick it
    /// is hot, as the numbers say, for the world of a seed.
    pub populate: Arc<Populate>,
    /// The numbers as the generation reads them: every one it knows,
    /// each missing as it is unless told otherwise, none it does not.
    pub numbers_read: fn(&GenerationNumbers) -> Vec<(String, u64)>,
    /// The numbers a window's sliders say.
    pub numbers_of_tuning: fn(&Tuning) -> Vec<(String, u64)>,
    /// Whether the world of a seed, as the numbers say, is one to start
    /// and be watched: what a seed drawn is tried for.
    pub fit_to_start: fn(&GenerationNumbers, u64) -> bool,
    /// The heights a world generated as the numbers say is drawn
    /// between.
    pub drawn_heights: fn(&GenerationNumbers) -> DrawnHeightRange,
    /// The heights asked for, of the world of a seed, as the numbers
    /// say, row by row.
    pub heights: fn(&GenerationNumbers, u64, &HeightsAsk) -> Vec<Height>,
    /// The map asked for, of the world of a seed, as the numbers say.
    pub map: fn(&GenerationNumbers, u64, MapAsk) -> MapAnswer,
}

impl std::fmt::Debug for WorldgenCode {
    /// Nothing of it: what generates the world, only its code knows.
    fn fmt(&self, formatter: &mut std::fmt::Formatter) -> std::fmt::Result {
        formatter.debug_struct("WorldgenCode").finish_non_exhaustive()
    }
}
