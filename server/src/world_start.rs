//! What a new world starts from ([`WorldStart`]): every number it is made
//! with, whoever gives them -- the command line (`commands::new`), or a
//! window's sliders ([`WorldStart::from_tuning`]). Its generation's
//! numbers are its generation's to read ([`WorldgenCode`]), the server
//! handing them on.

use crate::chunk_storage::disk::WorldInfo;
use crate::simulation::simulation_api::WorldgenCode;
use std::hash::{BuildHasher, RandomState};
use utilities::tuning::{Tuning, CAMERA_LOADS, FORCED_HOT, WORLD_SIDE};

/// Seeds tried after one drawn at random for one its generation finds
/// fit to start, before the one drawn is taken.
const START_TRIES: u64 = 256;

/// How far a world reaches, and whether it is hot throughout.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum WorldSize {
    /// No end: as far as coordinates reach, hot about its hot entities.
    NoEnd,
    /// `side` superchunks along a side, a square about its origin --
    /// nothing outside it ever made or hot -- hot about its hot
    /// entities, or `forced` hot throughout, whatever they do: only a
    /// world with an end can be.
    SquareOfSide {
        /// Superchunks along a side.
        side_superchunks: u32,
        /// Every superchunk of it hot throughout.
        forced_hot: bool,
    },
}

impl WorldSize {
    /// `side_superchunks` superchunks a side, 0 for no end; forced hot if `forced_hot`,
    /// or why not: only a world with a side can be.
    pub fn of_side(side_superchunks: u32, forced_hot: bool) -> Result<Self, String> {
        match side_superchunks {
            0 if forced_hot => Err("only a world with a side can be forced hot".to_string()),
            0 => Ok(Self::NoEnd),
            nonzero_side => Ok(Self::SquareOfSide { side_superchunks: nonzero_side, forced_hot }),
        }
    }
}

/// What a world starts from, for [`crate::start`]: every number,
/// whoever gives it (`docs/server.md`, "Made from a seed").
#[derive(Clone, Debug)]
pub struct WorldStart {
    /// The seed its superchunks are generated from.
    pub seed: u64,
    /// The numbers its superchunks are generated by, and what lives on
    /// them, each by name: one not among them as its generation has it
    /// unless told otherwise.
    pub generation_numbers: Vec<(String, u64)>,
    /// How far it reaches, and whether it is forced hot.
    pub world_size: WorldSize,
    /// Threads it ticks on, every one the machine has if none is given.
    pub thread_count: Option<usize>,
    /// Whether its camera loads superchunks: the viewport's hot. Nothing
    /// to a world forced hot, all of which is, nor to one run with no
    /// window.
    pub camera_loads: bool,
}

impl Default for WorldStart {
    /// Seed 1, generated as its generation has it unless told
    /// otherwise, no size to it, every thread the machine has, its
    /// camera loading nothing: what `new` makes unless told otherwise.
    fn default() -> Self {
        Self { seed: 1, generation_numbers: Vec::new(), world_size: WorldSize::NoEnd, thread_count: None, camera_loads: false }
    }
}

impl WorldStart {
    /// As a window's sliders have it (`utilities::tuning`), its
    /// generation's numbers as `worldgen` reads the sliders, from `seed`
    /// or one drawn ([`drawn_seed`]), on every thread
    /// (`docs/reference.md`, "WorldStart::from_tuning").
    pub fn from_tuning(seed: Option<u64>, tuning: &Tuning, worldgen: &WorldgenCode) -> Self {
        let generation_numbers = (worldgen.numbers_of_tuning)(tuning);
        let side_superchunks = tuning[WORLD_SIDE].round().max(0.0) as u32;
        let forced_hot = side_superchunks > 0 && tuning[FORCED_HOT] >= 0.5;
        let world_size = WorldSize::of_side(side_superchunks, forced_hot).expect("forced hot only with a side");
        let seed = seed.unwrap_or_else(|| drawn_seed(&generation_numbers, worldgen));
        Self { seed, generation_numbers, world_size, camera_loads: !forced_hot && tuning[CAMERA_LOADS] >= 0.5, ..Self::default() }
    }

    /// What the world `world_info` is of started from, as far as it says: its
    /// seed, generation, size and camera; on every thread the
    /// machine has.
    pub fn of_world(world_info: &WorldInfo) -> Self {
        let world_size = WorldSize::of_side(world_info.side_in_superchunks.unwrap_or(0), world_info.forced_hot).unwrap_or(WorldSize::NoEnd);
        Self { seed: world_info.seed, generation_numbers: world_info.generation_numbers.clone(), world_size, camera_loads: world_info.camera_loads, ..Self::default() }
    }
}

/// The first seed from `first_seed_tried` on whose world, generated as
/// `generation_numbers` say, `worldgen` finds fit to start.
pub fn seed_fit_to_start(first_seed_tried: u64, generation_numbers: &[(String, u64)], worldgen: &WorldgenCode) -> u64 {
    (first_seed_tried..).find(|&seed| (worldgen.fit_to_start)(generation_numbers, seed)).expect("a seed fit to start")
}

/// A seed drawn at random: the first from it `worldgen` finds fit to
/// start, generated as `generation_numbers` say, if one is within
/// [`START_TRIES`] -- else the one drawn.
pub fn drawn_seed(generation_numbers: &[(String, u64)], worldgen: &WorldgenCode) -> u64 {
    let random_seed = RandomState::new().hash_one(std::time::SystemTime::now());
    (random_seed..random_seed.saturating_add(START_TRIES)).find(|&seed| (worldgen.fit_to_start)(generation_numbers, seed)).unwrap_or(random_seed)
}
