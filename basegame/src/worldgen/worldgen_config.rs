//! The world generation's config files, in basegame's folder of the
//! world's mod config: a row a worldgen parameter, its name and its
//! value. The world's own ([`WORLDGEN_CONFIG_FILE`]), read as the
//! generation is set up -- none, and the generation is as it is unless
//! told otherwise -- and the one its reset is to take
//! ([`RESET_CONFIG_FILE`]), written as a parameter is set for it and put
//! in the world's place as the world is reset. The server reads neither.

use crate::worldgen::WorldGeneration;
use std::path::Path;
use utilities::csv;

/// The world's config file's name, in basegame's mod config folder: what
/// it is generated by.
pub const WORLDGEN_CONFIG_FILE: &str = "worldgen.csv";
/// The config file of the world's reset, in the same folder: what it is
/// to be generated by once reset.
pub const RESET_CONFIG_FILE: &str = "worldgen_for_reset.csv";
/// Their columns.
const CONFIG_COLUMNS: [&str; 2] = ["parameter", "value"];

impl WorldGeneration {
    /// It as the world's config file in `config_folder` says, a parameter
    /// the file does not name as it is -- all as it is if there is no
    /// file. Or why the file is unreadable.
    pub fn read_config(self, config_folder: &Path) -> Result<Self, String> {
        self.read_file(&config_folder.join(WORLDGEN_CONFIG_FILE))
    }

    /// It as the world's reset is to be generated, the config files in
    /// `config_folder` say: the world's own, and over it what was set for
    /// the reset. Or why a file is unreadable.
    pub fn read_reset_config(self, config_folder: &Path) -> Result<Self, String> {
        self.read_config(config_folder)?.read_file(&config_folder.join(RESET_CONFIG_FILE))
    }

    /// It written as the world's config file in `config_folder`, the
    /// folder made if it is not there. Or why not.
    pub fn write_config(&self, config_folder: &Path) -> Result<(), String> {
        self.write_file(config_folder, WORLDGEN_CONFIG_FILE)
    }

    /// It written as the config file of the world's reset in
    /// `config_folder`, the folder made if it is not there. Or why not.
    pub fn write_reset_config(&self, config_folder: &Path) -> Result<(), String> {
        self.write_file(config_folder, RESET_CONFIG_FILE)
    }

    /// It as the config file at `config_path` says, a parameter it does
    /// not name as it is -- all as it is if there is no file. Or why the
    /// file is unreadable.
    fn read_file(self, config_path: &Path) -> Result<Self, String> {
        let Ok(config_text) = std::fs::read_to_string(config_path) else {
            return Ok(self);
        };
        let mut csv_rows = csv::rows_with_header(&config_text).into_iter();
        if csv_rows.next().is_none_or(|first_row| first_row != CONFIG_COLUMNS) {
            return Err(format!("{}: does not start with `{}`", config_path.display(), CONFIG_COLUMNS.join(",")));
        }
        let worldgen_parameters = csv_rows
            .map(|csv_row| match &csv_row[..] {
                [name, value] => value.parse().map(|value| (name.clone(), value)).map_err(|_| format!("{}: `{value}` is not a number", config_path.display())),
                _ => Err(format!("{}: `{}` is not a parameter and its value", config_path.display(), csv_row.join(","))),
            })
            .collect::<Result<Vec<_>, String>>()?;
        Ok(self.with_worldgen_parameters(&worldgen_parameters))
    }

    /// It written as the config file `file_name` in `config_folder`, the
    /// folder made if it is not there. Or why not.
    fn write_file(&self, config_folder: &Path, file_name: &str) -> Result<(), String> {
        std::fs::create_dir_all(config_folder).map_err(|error| format!("{}: {error}", config_folder.display()))?;
        let config_text = csv::row_text(&CONFIG_COLUMNS) + &self.worldgen_parameters().iter().map(|(name, value)| csv::row_text(&[name.as_str(), &value.to_string()])).collect::<String>();
        let config_path = config_folder.join(file_name);
        std::fs::write(&config_path, config_text).map_err(|error| format!("{}: {error}", config_path.display()))
    }
}
